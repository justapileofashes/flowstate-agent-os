// One-time generator for the Flowstate license ISSUER keypair (ES256 / P-256).
//
//   node scripts/gen-issuer-key.mjs
//
// Writes:
//   license-keys/issuer-private.jwk          <- YOUR PRIVATE KEY (gitignored). Back it up.
//   src/main/services/license-issuer-key.ts  <- public key, embedded in the app.
//
// The private key signs license keys (scripts/issue-license.mjs). The public key
// ships in the app and only VERIFIES — safe to embed, cannot forge.
//
// Run ONCE. Re-running rotates the key and invalidates every license already
// issued. If license-keys/issuer-private.jwk already exists, this refuses to run.
import { generateKeyPairSync } from 'node:crypto';
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const privPath = resolve(root, 'license-keys/issuer-private.jwk');
const pubModulePath = resolve(root, 'src/main/services/license-issuer-key.ts');
const KID = 'flowstate-license-1';

if (existsSync(privPath)) {
  console.error(`Refusing to overwrite existing private key at ${privPath}`);
  console.error('Delete it manually only if you intend to rotate (invalidates all issued keys).');
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });

const privJwk = privateKey.export({ format: 'jwk' });
const pubJwk = publicKey.export({ format: 'jwk' });
const meta = { kid: KID, alg: 'ES256', use: 'sig' };

mkdirSync(dirname(privPath), { recursive: true });
writeFileSync(privPath, JSON.stringify({ ...privJwk, ...meta }, null, 2));

const pubFull = { ...pubJwk, ...meta };
const module = `// AUTO-GENERATED by scripts/gen-issuer-key.mjs — do not edit by hand.
// The PUBLIC half of the Flowstate license issuer key. Safe to ship: it only
// verifies license keys, it cannot sign/forge them. The private half lives in
// license-keys/issuer-private.jwk (gitignored) and is used by scripts/issue-license.mjs.
import type { JwkSet } from './license-service';

export const ISSUER_KID = ${JSON.stringify(KID)};

export const ISSUER_JWKS: JwkSet = {
  keys: [${JSON.stringify(pubFull)}],
};
`;
writeFileSync(pubModulePath, module);

console.log('Issuer keypair generated.');
console.log(`  PRIVATE (keep safe, gitignored): ${privPath}`);
console.log(`  PUBLIC  (embedded in app):       ${pubModulePath}`);
console.log('');
console.log('IMPORTANT: back up license-keys/issuer-private.jwk somewhere safe.');
console.log('Lose it = you can never issue new keys. Leak it = anyone can forge licenses.');
